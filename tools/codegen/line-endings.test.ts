import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { expect, it } from "vitest";

import { copyGenerators } from "./copy.mjs";
import { toLf } from "./line-endings.mjs";
import { publishModels } from "./protocol.mjs";

const LF = "export const id = 1;\n";
const CRLF = "export const id = 1;\r\n";

it("does not match an LF index when generated bytes keep CRLF", () => {
  expect(CRLF).not.toBe(LF);
  expect(CRLF.includes("\r")).toBe(true);
});

it("matches an LF index when generated text is normalized", () => {
  expect(toLf(CRLF)).toBe(LF);
  expect(toLf("a\r\nb\n")).toBe("a\nb\n");
  expect(toLf("a\rb")).toBe("a\nb");
  expect(toLf(LF)).toBe(LF);
});

it("writes LF when copyGenerators reads a CRLF source", async () => {
  const root = mkdtempSync(path.join(tmpdir(), "oi-lf-copy-"));
  try {
    writeFileSync(path.join(root, "source.ts"), CRLF);
    await copyGenerators(root, [
      { input: "source.ts", output: "source.gen.ts" },
    ]);
    const output = readFileSync(path.join(root, "source.gen.ts"), "utf8");
    expect(output).toBe(LF);
    expect(output.includes("\r")).toBe(false);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

it("publishes LF when the staged protocol model is CRLF", async () => {
  const root = mkdtempSync(path.join(tmpdir(), "oi-lf-proto-"));
  const staged = "class M:\r\n    x: int\r\n";
  const expected = "class M:\n    x: int\n";
  try {
    const modelDir = path.join(root, "stage");
    const outputDir = path.join(root, "out");
    mkdirSync(modelDir);
    mkdirSync(outputDir);
    writeFileSync(path.join(modelDir, "model.py"), staged);
    expect(staged).not.toBe(expected);
    await publishModels(outputDir, modelDir);
    const output = readFileSync(path.join(outputDir, "model.py"), "utf8");
    expect(output).toBe(expected);
    expect(output.includes("\r")).toBe(false);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

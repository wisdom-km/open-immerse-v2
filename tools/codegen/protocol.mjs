import { copyFile, mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { canonicalJson } from "./canonical-json.mjs";
import { assertPinned, run } from "./command.mjs";
import { loadProtocolSchemas } from "./schema-module.mjs";

const generatorFlags = [
  "--input-file-type",
  "jsonschema",
  "--output-model-type",
  "pydantic_v2.BaseModel",
  "--target-python-version",
  "3.11",
  "--disable-timestamp",
  "--use-double-quotes",
  "--extra-fields",
  "ignore",
  "--enum-field-as-literal",
  "all",
  "--field-constraints",
  "--snake-case-field",
  "--formatters",
  "builtin",
  "--no-allow-remote-refs",
];

const generatedInit = '"""Generated by tools/codegen. Do not edit."""\n';

export async function generateProtocol(options) {
  const pinned = await readPin(options.pinPath);
  const reported = uv(options.parserRoot, ["datamodel-codegen", "--version"]);
  assertPinned(reported, pinned);
  const schemas = await loadProtocolSchemas(options.schemaPath);
  const staging = await mkdirTemp();
  try {
    const schemaDir = path.join(staging, "schemas");
    const modelDir = path.join(staging, "protocol");
    await mkdir(schemaDir);
    await mkdir(modelDir);
    await writeSchemas(schemaDir, schemas);
    uv(options.parserRoot, [
      "datamodel-codegen",
      "--input",
      schemaDir,
      "--output",
      modelDir,
      ...generatorFlags,
    ]);
    await writeFile(path.join(modelDir, "__init__.py"), generatedInit);
    await formatModels(options.parserRoot, modelDir);
    await publishModels(options.outputDir, modelDir);
  } finally {
    await rm(staging, { recursive: true, force: true });
  }
}

async function readPin(pinPath) {
  const parsed = JSON.parse(await readFile(pinPath, "utf8"));
  if (!parsed || typeof parsed !== "object") {
    throw new Error("codegen pin");
  }
  const pinned = parsed.datamodelCodeGenerator;
  if (typeof pinned !== "string" || pinned === "") {
    throw new Error("codegen pin");
  }
  return pinned;
}

function mkdirTemp() {
  return mkdtemp(path.join(tmpdir(), "oigen-"));
}

async function writeSchemas(schemaDir, schemas) {
  for (const item of schemas) {
    await writeFile(path.join(schemaDir, `${item.name}.json`), canonicalJson(item.schema));
  }
}

function uv(parserRoot, args) {
  return run("uv", ["run", "--frozen", "--extra", "dev", "--directory", parserRoot, ...args], parserRoot);
}

async function formatModels(parserRoot, modelDir) {
  const files = (await readdir(modelDir))
    .filter((name) => name.endsWith(".py"))
    .sort()
    .map((name) => path.join(modelDir, name));
  const config = path.join(parserRoot, "pyproject.toml");
  uv(parserRoot, ["ruff", "check", "--fix", "--no-cache", "--config", config, ...files]);
  uv(parserRoot, ["ruff", "format", "--no-cache", "--config", config, ...files]);
  uv(parserRoot, ["ruff", "check", "--no-cache", "--config", config, ...files]);
}

async function publishModels(outputDir, modelDir) {
  await mkdir(outputDir, { recursive: true });
  const staged = (await readdir(modelDir)).filter((name) => name.endsWith(".py")).sort();
  const current = await readdir(outputDir);
  for (const name of current) {
    if (name.endsWith(".py") && !staged.includes(name)) {
      await rm(path.join(outputDir, name));
    }
  }
  for (const name of staged) {
    await copyFile(path.join(modelDir, name), path.join(outputDir, name));
  }
}

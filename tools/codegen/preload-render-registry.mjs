export function renderRegistry(descriptors) {
  const entries = descriptors.map(renderEntry);
  const body = entries.length === 0 ? "" : `\n${entries.join(",\n")},\n`;
  return `${header}\n\n${types}\n\nexport const ipcRegistry: readonly IpcRegistryEntry[] = [${body}];\n`;
}

function renderEntry(descriptor) {
  if (descriptor.kind === "event") {
    return [
      "  {",
      '    kind: "event",',
      `    channel: ${JSON.stringify(descriptor.channel)},`,
      `    payload: ${schemaLiteral(descriptor.payload)},`,
      "  }",
    ].join("\n");
  }
  const request =
    descriptor.request === null ? "null" : schemaLiteral(descriptor.request);
  return [
    "  {",
    '    kind: "command",',
    `    channel: ${JSON.stringify(descriptor.channel)},`,
    `    idempotent: ${String(descriptor.idempotent)},`,
    `    request: ${request},`,
    `    response: ${schemaLiteral(descriptor.response)},`,
    "  }",
  ].join("\n");
}

function schemaLiteral(schema) {
  return JSON.stringify(sortKeys(schema), null, 2)
    .split("\n")
    .map((line, index) => (index === 0 ? line : `    ${line}`))
    .join("\n");
}

function sortKeys(value) {
  if (Array.isArray(value)) {
    return value.map(sortKeys);
  }
  if (value !== null && typeof value === "object") {
    const sorted = {};
    for (const key of Object.keys(value).sort()) {
      sorted[key] = sortKeys(value[key]);
    }
    return sorted;
  }
  return value;
}

function writeIpc(root: string, source: string): Promise<void> {
  mkdirSync(path.join(root, "ipc"), { recursive: true });
  return writeFile(path.join(root, "ipc", "sample.ts"), source);
}

function readOutputs(root: string): string {
  return outputs
    .map((file) => {
      try {
        return readFileSync(path.join(root, file), "utf8");
      } catch {
        return "";
      }
    })
    .join("\n");
}

type Bridge = {
  invoke: (channel: string, payload: unknown) => Promise<unknown>;
  subscribe: (
    channel: string,
    listener: (payload: unknown) => void,
  ) => () => void;
};

type CreateOi = (bridge: Bridge) => Record<string, unknown>;

async function loadCreateOi(file: string): Promise<CreateOi> {
  const source = readFileSync(file, "utf8");
  const compiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ES2022,
      target: ts.ScriptTarget.ES2022,
    },
    fileName: file,
  }).outputText;
  const out = `${file}.mjs`;
  await writeFile(out, compiled);
  const imported = (await import(
    `${pathToFileURL(out).href}?t=${String(Date.now())}`
  )) as {
    createOi: CreateOi;
  };
  return imported.createOi;
}

function keyPaths(value: unknown, prefix = ""): string[] {
  if (typeof value === "function") {
    return prefix === "" ? [] : [prefix];
  }
  if (typeof value !== "object" || value === null) {
    return [];
  }
  const paths: string[] = [];
  for (const key of Object.keys(value).sort()) {
    const next = prefix === "" ? key : `${prefix}.${key}`;
    paths.push(...keyPaths(record(value)[key], next));
  }
  return paths;
}

function record(value: object): Record<string, unknown> {
  return value as Record<string, unknown>;
}

async function callOpen(oi: Record<string, unknown>): Promise<void> {
  const library = record(objectChild(oi, "library"));
  await asOpen(library.open)({ id: "doc-1" });
}

function callProgress(oi: Record<string, unknown>): () => void {
  const settings = record(objectChild(oi, "settings"));
  const dataDir = record(objectChild(settings, "dataDir"));
  return asVoid(asProgress(dataDir.onRelocateProgress)(() => undefined));
}

function asOpen(
  value: unknown,
): (input: { readonly id: string }) => Promise<unknown> {
  if (typeof value !== "function") {
    throw new Error("library.open");
  }
  return value as (input: { readonly id: string }) => Promise<unknown>;
}

function asProgress(value: unknown): (listener: () => void) => unknown {
  if (typeof value !== "function") {
    throw new Error("onRelocateProgress");
  }
  return value as (listener: () => void) => unknown;
}

function asVoid(value: unknown): () => void {
  if (typeof value !== "function") {
    throw new Error("unsubscribe");
  }
  return value as () => void;
}

function objectChild(value: object, key: string): object {
  const child = record(value)[key];
  if (typeof child !== "object" || child === null) {
    throw new Error(key);
  }
  return child;
}

import { renderErrorUnion, renderOiError } from "./preload-render-error.mjs";
import { renderResponse } from "./preload-schema-type.mjs";
import { buildTree, sortedKeys } from "./preload-tree.mjs";

const header = "// Generated by tools/codegen. Do not edit.";

export function renderTypes(descriptors) {
  const commands = descriptors.filter((item) => item.kind === "command");
  const parts = [header, ""];
  if (commands.length > 0) {
    parts.push(resultType(), "");
  }
  parts.push(
    renderOiError(commands).trimEnd(),
    "",
    renderWindow(descriptors),
    "",
  );
  return parts.join("\n");
}

function resultType() {
  return [
    "type Result<T, E> =",
    "  | { readonly ok: true; readonly value: T }",
    "  | { readonly ok: false; readonly error: E };",
  ].join("\n");
}

function renderWindow(descriptors) {
  const oi =
    descriptors.length === 0
      ? "Record<string, never>"
      : renderNode(buildTree(descriptors), 2);
  return [
    "declare global {",
    "  interface Window {",
    `    readonly oi: ${oi};`,
    "  }",
    "}",
  ].join("\n");
}

function renderNode(node, depth) {
  const pad = "  ".repeat(depth);
  const lines = sortedKeys(node).map((key) => renderMember(node, key, depth));
  return `{\n${lines.join("\n")}\n${pad.slice(2)}}`;
}

function renderMember(node, key, depth) {
  const pad = "  ".repeat(depth);
  const child = node.children.get(key);
  if (child !== undefined) {
    return `${pad}readonly ${key}: ${renderNode(child, depth + 1)};`;
  }
  const descriptor = node.methods.get(key);
  if (descriptor === undefined) {
    throw new Error("ipc channel");
  }
  if (descriptor.kind === "event") {
    return renderEvent(descriptor, pad);
  }
  return renderCommand(descriptor, pad);
}

function renderCommand(descriptor, pad) {
  const name = descriptor.channel.split(".").at(-1);
  const input =
    descriptor.transport === "dropped-file"
      ? "file: File"
      : descriptor.request === null
        ? ""
        : `input: ${renderResponse(descriptor.request)}`;
  const result = `Promise<Result<${renderResponse(descriptor.response)}, ${renderErrorUnion(descriptor.errors)}>>`;
  return [
    `${pad}/** idempotent: ${String(descriptor.idempotent)} */`,
    `${pad}${name}(${input}): ${result};`,
  ].join("\n");
}

function renderEvent(descriptor, pad) {
  const name = descriptor.channel.split(".").at(-1);
  return `${pad}${name}(listener: (payload: ${renderResponse(descriptor.payload)}) => void): () => void;`;
}

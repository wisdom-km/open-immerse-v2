import { renderErrorUnion } from "./preload-render-error.mjs";
import { renderResponse } from "./preload-schema-type.mjs";
import { buildTree, sortedKeys } from "./preload-tree.mjs";

const header = "// Generated by tools/codegen. Do not edit.";

export function renderPreload(descriptors) {
  const commands = descriptors.filter((item) => item.kind === "command");
  const events = descriptors.filter((item) => item.kind === "event");
  const dropped = commands.some((item) => item.transport === "dropped-file");
  const parts = [header, "", bridgeType(dropped)];
  if (commands.length > 0) {
    parts.push("", resultType(), "", callHelper());
  }
  if (dropped) {
    parts.push("", callDroppedHelper());
  }
  if (events.length > 0) {
    parts.push("", listenHelper());
  }
  parts.push("", renderCreate(descriptors), "");
  return parts.join("\n");
}

function bridgeType(dropped) {
  const lines = [
    "export type IpcBridge = {",
    "  invoke(channel: string, payload: unknown): Promise<unknown>;",
  ];
  if (dropped) {
    lines.push(
      "  invokeDropped(",
      "    channel: string,",
      "    file: File,",
      "    payload: unknown,",
      "  ): Promise<unknown>;",
    );
  }
  lines.push(
    "  subscribe(",
    "    channel: string,",
    "    listener: (payload: unknown) => void,",
    "  ): () => void;",
    "};",
  );
  return lines.join("\n");
}

function resultType() {
  return [
    "type Result<T, E> =",
    "  | { readonly ok: true; readonly value: T }",
    "  | { readonly ok: false; readonly error: E };",
  ].join("\n");
}

function callHelper() {
  return [
    "function call<T>(",
    "  bridge: IpcBridge,",
    "  channel: string,",
    "  payload: unknown,",
    "): Promise<T> {",
    "  return bridge.invoke(channel, payload) as Promise<T>;",
    "}",
  ].join("\n");
}

function callDroppedHelper() {
  return [
    "function callDropped<T>(",
    "  bridge: IpcBridge,",
    "  channel: string,",
    "  file: File,",
    "  payload: unknown,",
    "): Promise<T> {",
    "  return bridge.invokeDropped(channel, file, payload) as Promise<T>;",
    "}",
  ].join("\n");
}

function listenHelper() {
  return [
    "function listen<T>(",
    "  bridge: IpcBridge,",
    "  channel: string,",
    "  listener: (payload: T) => void,",
    "): () => void {",
    "  return bridge.subscribe(channel, (payload: unknown) => {",
    "    listener(payload as T);",
    "  });",
    "}",
  ].join("\n");
}

function renderCreate(descriptors) {
  if (descriptors.length === 0) {
    return [
      "export function createOi(bridge: IpcBridge): Record<string, never> {",
      "  // No descriptor is exposed, so oi has no keys.",
      "  for (const key of Object.keys(bridge)) {",
      '    if (key === "") {',
      "      return {};",
      "    }",
      "  }",
      "  return {};",
      "}",
    ].join("\n");
  }
  const body = renderNode(buildTree(descriptors), 1);
  return `export function createOi(bridge: IpcBridge) {\n  return ${body};\n}`;
}

function renderNode(node, depth) {
  const pad = "  ".repeat(depth);
  const lines = sortedKeys(node).map((key) => renderMember(node, key, depth));
  return `{\n${lines.join("\n")}\n${pad.slice(2)}}`;
}

function renderMember(node, key, depth) {
  const pad = "  ".repeat(depth);
  const child = node.children.get(key);
  if (child !== undefined) {
    return `${pad}${key}: ${renderNode(child, depth + 1)},`;
  }
  const descriptor = node.methods.get(key);
  if (descriptor === undefined) {
    throw new Error("ipc channel");
  }
  if (descriptor.kind === "event") {
    return renderEvent(descriptor, pad);
  }
  return renderCommand(descriptor, pad);
}

function renderCommand(descriptor, pad) {
  if (descriptor.transport === "dropped-file") {
    return renderDropped(descriptor, pad);
  }
  const name = descriptor.channel.split(".").at(-1);
  const input =
    descriptor.request === null
      ? ""
      : `input: ${renderResponse(descriptor.request)}`;
  const payload = descriptor.request === null ? "undefined" : "input";
  return [
    `${pad}/** idempotent: ${String(descriptor.idempotent)} */`,
    `${pad}${name}(${input}): ${commandResult(descriptor)} {`,
    `${pad}  return call(bridge, ${JSON.stringify(descriptor.channel)}, ${payload});`,
    `${pad}},`,
  ].join("\n");
}

function renderDropped(descriptor, pad) {
  const name = descriptor.channel.split(".").at(-1);
  const payload = descriptor.request === null ? "undefined" : "{}";
  return [
    `${pad}/** idempotent: ${String(descriptor.idempotent)} */`,
    `${pad}${name}(file: File): ${commandResult(descriptor)} {`,
    `${pad}  return callDropped(`,
    `${pad}    bridge,`,
    `${pad}    ${JSON.stringify(descriptor.channel)},`,
    `${pad}    file,`,
    `${pad}    ${payload},`,
    `${pad}  );`,
    `${pad}},`,
  ].join("\n");
}

function commandResult(descriptor) {
  return `Promise<Result<${renderResponse(descriptor.response)}, ${renderErrorUnion(descriptor.errors)}>>`;
}

function renderEvent(descriptor, pad) {
  const name = descriptor.channel.split(".").at(-1);
  return [
    `${pad}${name}(`,
    `${pad}  listener: (payload: ${renderResponse(descriptor.payload)}) => void,`,
    `${pad}): () => void {`,
    `${pad}  return listen(bridge, ${JSON.stringify(descriptor.channel)}, listener);`,
    `${pad}},`,
  ].join("\n");
}
